func TestCreateTableStatements_Errors(t *testing.T) {
	tests := []struct {
		name     string
		schema   domain.TableSchema
		sentinel error
	}{
		{"no table name", domain.TableSchema{}, domain.ErrInvalidSchema},
		{"no column name", domain.TableSchema{Name: "t", Columns: []domain.ColumnDefinition{{}}}, domain.ErrInvalidSchema},
		{"bad default", domain.TableSchema{Name: "t", Columns: []domain.ColumnDefinition{{Name: "c", DefaultValue: []int{1}}}}, domain.ErrInvalidSchema},
		{"check constraint", domain.TableSchema{Name: "t", Constraints: []domain.ConstraintDefinition{{Type: domain.ConstraintTypeCheck, Columns: []string{"c"}}}}, domain.ErrUnsupportedOperation},
		{"constraint without columns", domain.TableSchema{Name: "t", Constraints: []domain.ConstraintDefinition{{Type: domain.ConstraintTypeUnique}}}, domain.ErrInvalidSchema},
		{"foreign key without table", domain.TableSchema{Name: "t", Constraints: []domain.ConstraintDefinition{{Type: domain.ConstraintTypeForeignKey, Columns: []string{"c"}}}}, domain.ErrInvalidSchema},
		{"bad referential action", domain.TableSchema{Name: "t", Constraints: []domain.ConstraintDefinition{{Type: domain.ConstraintTypeForeignKey, Columns: []string{"c"}, RefTable: "r", OnUpdate: 99}}}, domain.ErrInvalidSchema},
		{"unknown constraint type", domain.TableSchema{Name: "t", Constraints: []domain.ConstraintDefinition{{Type: 99, Columns: []string{"c"}}}}, domain.ErrInvalidSchema},
		{"index without columns", domain.TableSchema{Name: "t", Indexes: []domain.IndexDefinition{{Name: "i"}}}, domain.ErrInvalidSchema},
		{"unknown index type", domain.TableSchema{Name: "t", Indexes: []domain.IndexDefinition{{Columns: []string{"c"}, Type: 99}}}, domain.ErrInvalidSchema},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := createTableStatements(tt.schema)
			assert.ErrorIs(t, err, tt.sentinel)
		})
	}
}

func TestAlterTableStatements(t *testing.T) {
	tests := []struct {
		name   string
		table  string
		change domain.SchemaChange
		want   string
	}{
		{
			name:   "add column",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeAddColumn, Column: domain.ColumnDefinition{Name: "nick", DataType: domain.DataTypeString, Nullable: true, DefaultValue: "n/a"}},
			want:   `ALTER TABLE "users" ADD COLUMN "nick" TEXT DEFAULT 'n/a'`,
		},
		{
			name:   "drop column",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeDropColumn, Column: domain.ColumnDefinition{Name: "nick"}},
			want:   `ALTER TABLE "users" DROP COLUMN "nick"`,
		},
		{
			name:   "modify column: type, nullability and default",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeModifyColumn, Column: domain.ColumnDefinition{Name: "email", DataType: domain.DataTypeString, Length: 320, DefaultValue: "none"}},
			want:   `ALTER TABLE "users" ALTER COLUMN "email" TYPE VARCHAR(320), ALTER COLUMN "email" SET NOT NULL, ALTER COLUMN "email" SET DEFAULT 'none'`,
		},
		{
			name:   "modify column: nullable without default",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeModifyColumn, Column: domain.ColumnDefinition{Name: "bio", DataType: domain.DataTypeText, Nullable: true}},
			want:   `ALTER TABLE "users" ALTER COLUMN "bio" TYPE TEXT, ALTER COLUMN "bio" DROP NOT NULL, ALTER COLUMN "bio" DROP DEFAULT`,
		},
		{
			name:   "modify identity column keeps its default",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeModifyColumn, Column: domain.ColumnDefinition{Name: "id", DataType: domain.DataTypeInteger, Nullable: true, AutoIncrement: true, PrimaryKey: true}},
			want:   `ALTER TABLE "users" ALTER COLUMN "id" TYPE INTEGER, ALTER COLUMN "id" SET NOT NULL`,
		},
		{
			name:   "add index",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeAddIndex, Index: domain.IndexDefinition{Name: "users_tags_idx", Columns: []string{"tags"}, Type: domain.IndexTypeGIN}},
			want:   `CREATE INDEX "users_tags_idx" ON "users" USING gin ("tags")`,
		},
		{
			name:   "drop index",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeDropIndex, Index: domain.IndexDefinition{Name: "users_tags_idx"}},
			want:   `DROP INDEX "users_tags_idx"`,
		},
		{
			name:   "drop index of a schema-qualified table",
			table:  "app.users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeDropIndex, Index: domain.IndexDefinition{Name: "users_tags_idx"}},
			want:   `DROP INDEX "app"."users_tags_idx"`,
		},
		{
			name:   "add constraint",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeAddConstraint, Constraint: domain.ConstraintDefinition{Name: "pk", Type: domain.ConstraintTypePrimaryKey, Columns: []string{"id"}}},
			want:   `ALTER TABLE "users" ADD CONSTRAINT "pk" PRIMARY KEY ("id")`,
		},
		{
			name:   "drop constraint",
			table:  "users",
			change: domain.SchemaChange{Type: domain.SchemaChangeTypeDropConstraint, Constraint: domain.ConstraintDefinition{Name: "pk"}},
			want:   `ALTER TABLE "users" DROP CONSTRAINT "pk"`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := alterTableStatements(tt.table, tt.change)
			require.NoError(t, err)
			assert.Equal(t, []string{tt.want}, got)
		})
	}

	for name, change := range map[string]domain.SchemaChange{
		"unknown change":             {Type: 99},
		"drop column without name":   {Type: domain.SchemaChangeTypeDropColumn},
		"modify column without name": {Type: domain.SchemaChangeTypeModifyColumn},
		"drop index without name":    {Type: domain.SchemaChangeTypeDropIndex},
		"drop constraint w/o name":   {Type: domain.SchemaChangeTypeDropConstraint},
		"bad default":                {Type: domain.SchemaChangeTypeModifyColumn, Column: domain.ColumnDefinition{Name: "c", DefaultValue: struct{}{}}},
		"add check constraint":       {Type: domain.SchemaChangeTypeAddConstraint, Constraint: domain.ConstraintDefinition{Type: domain.ConstraintTypeCheck}},
		"add index without columns":  {Type: domain.SchemaChangeTypeAddIndex},
		"add column without name":    {Type: domain.SchemaChangeTypeAddColumn},
	} {
		_, err := alterTableStatements("t", change)
		assert.Error(t, err, name)
	}
	_, err := alterTableStatements("t", domain.SchemaChange{Type: 99})
	assert.ErrorIs(t, err, domain.ErrUnsupportedOperation)
}

func TestColumnType(t *testing.T) {
	tests := map[domain.DataType]string{
		domain.DataTypeString:   "TEXT",
		domain.DataTypeInteger:  "INTEGER",
		domain.DataTypeFloat:    "DOUBLE PRECISION",
		domain.DataTypeBoolean:  "BOOLEAN",
		domain.DataTypeDateTime: "TIMESTAMP",
		domain.DataTypeDate:     "DATE",
		domain.DataTypeTime:     "TIME",
		domain.DataTypeBinary:   "BYTEA",
		domain.DataTypeJSON:     "JSONB",
		domain.DataTypeUUID:     "UUID",
		domain.DataTypeArray:    "TEXT[]",
		domain.DataTypeDecimal:  "NUMERIC",
		domain.DataTypeText:     "TEXT",
		domain.DataTypeUnknown:  "TEXT",
	}
	for dt, want := range tests {
		assert.Equal(t, want, columnType(domain.ColumnDefinition{DataType: dt}), dt.String())
	}
	assert.Equal(t, "NUMERIC(12)", columnType(domain.ColumnDefinition{DataType: domain.DataTypeDecimal, Precision: 12}))
}

func TestReferentialActions(t *testing.T) {
	for action, want := range map[domain.ReferentialAction]string{
		domain.ReferentialActionNoAction:   "",
		domain.ReferentialActionRestrict:   " ON UPDATE RESTRICT ON DELETE RESTRICT",
		domain.ReferentialActionCascade:    " ON UPDATE CASCADE ON DELETE CASCADE",
		domain.ReferentialActionSetNull:    " ON UPDATE SET NULL ON DELETE SET NULL",
		domain.ReferentialActionSetDefault: " ON UPDATE SET DEFAULT ON DELETE SET DEFAULT",
	} {
		def, err := constraintDefinition(domain.ConstraintDefinition{
			Type: domain.ConstraintTypeForeignKey, Columns: []string{"a"}, RefTable: "r", OnUpdate: action, OnDelete: action,
		})
		require.NoError(t, err)
		assert.Equal(t, `FOREIGN KEY ("a") REFERENCES "r"`+want, def)
	}
}

// Invalid schema requests fail before any statement is sent (no pool needed).
func TestStorage_SchemaValidation(t *testing.T) {
	s := newStorage(nil, domain.Config{}, NewAdapter().(*Adapter), 0)
	ctx := t.Context()

	assert.ErrorIs(t, s.CreateTable(ctx, domain.TableSchema{}), domain.ErrInvalidSchema)
	assert.ErrorIs(t, s.DropTable(ctx, ""), domain.ErrInvalidSchema)
	assert.ErrorIs(t, s.AlterTable(ctx, "", nil), domain.ErrInvalidSchema)
	assert.ErrorIs(t, s.AlterTable(ctx, "t", []domain.SchemaChange{{Type: 99}}), domain.ErrUnsupportedOperation)
	assert.NoError(t, s.AlterTable(ctx, "t", nil), "no changes, nothing to do")
}

func TestQuoteIdentifiers(t *testing.T) {
	assert.Equal(t, `"users"`, quoteTable("users"))
	assert.Equal(t, `"app"."users"`, quoteTable("app.users"))
	assert.Equal(t, `"a ""b"""`, quoteIdent(`a "b"`))
	assert.Equal(t, `"x; DROP TABLE y"`, quoteIdent("x; DROP TABLE y"))
}
