// quoteIdent quotes a single identifier (column, index, constraint or savepoint
// name).
func quoteIdent(name string) string {
	return pgx.Identifier{name}.Sanitize()
}

// quoteTable quotes a table name, treating dots as schema separators
// ("app.users" -> "app"."users").
func quoteTable(name string) string {
	return pgx.Identifier(strings.Split(name, ".")).Sanitize()
}

func invalidSchema(format string, args ...interface{}) *domain.StorageError {
	return domain.NewSchemaError("INVALID_SCHEMA", fmt.Sprintf(format, args...))
}

// createTableStatements renders CREATE TABLE (columns and table constraints)
// followed by one CREATE INDEX per index.
func createTableStatements(schema domain.TableSchema) ([]string, error) {
	if schema.Name == "" {
		return nil, invalidSchema("table name is required")
	}

	primaryKeys := 0
	for _, col := range schema.Columns {
		if col.PrimaryKey {
			primaryKeys++
		}
	}

	defs := make([]string, 0, len(schema.Columns)+len(schema.Constraints)+1)
	var keyColumns []string
	for _, col := range schema.Columns {
		def, err := columnDefinition(col, primaryKeys == 1)
		if err != nil {
			return nil, err
		}
		defs = append(defs, def)
		if col.PrimaryKey {
			keyColumns = append(keyColumns, col.Name)
		}
	}
	if primaryKeys > 1 { // composite key: a table constraint
		defs = append(defs, "PRIMARY KEY ("+quoteIdents(keyColumns)+")")
	}
	for _, c := range schema.Constraints {
		def, err := constraintDefinition(c)
		if err != nil {
			return nil, err
		}
		defs = append(defs, def)
	}

	statements := []string{fmt.Sprintf("CREATE TABLE %s (%s)", quoteTable(schema.Name), strings.Join(defs, ", "))}
	for _, idx := range schema.Indexes {
		stmt, err := createIndexStatement(schema.Name, idx)
		if err != nil {
			return nil, err
		}
		statements = append(statements, stmt)
	}
	return statements, nil
}

// columnDefinition renders a column for CREATE TABLE / ADD COLUMN. inlinePK adds
// PRIMARY KEY for a primary key column (false when the table has a composite key).
func columnDefinition(col domain.ColumnDefinition, inlinePK bool) (string, error) {
	if col.Name == "" {
		return "", invalidSchema("column name is required")
	}

	parts := []string{quoteIdent(col.Name), columnType(col)}
	if col.AutoIncrement {
		parts = append(parts, "GENERATED BY DEFAULT AS IDENTITY")
	}
	if !col.Nullable {
		parts = append(parts, "NOT NULL")
	}
	if col.DefaultValue != nil {
		literal, err := quoteLiteral(col.DefaultValue)
		if err != nil {
			return "", invalidSchema("column %s: %v", col.Name, err)
		}
		parts = append(parts, "DEFAULT "+literal)
	}
	if col.PrimaryKey && inlinePK {
		parts = append(parts, "PRIMARY KEY")
	}
	return strings.Join(parts, " "), nil
}

// alterTableStatements renders one schema change.
func alterTableStatements(table string, change domain.SchemaChange) ([]string, error) {
	alter := "ALTER TABLE " + quoteTable(table) + " "
	switch change.Type {
	case domain.SchemaChangeTypeAddColumn:
		def, err := columnDefinition(change.Column, true)
		if err != nil {
			return nil, err
		}
		return []string{alter + "ADD COLUMN " + def}, nil

	case domain.SchemaChangeTypeDropColumn:
		if change.Column.Name == "" {
			return nil, invalidSchema("column name is required")
		}
		return []string{alter + "DROP COLUMN " + quoteIdent(change.Column.Name)}, nil

	case domain.SchemaChangeTypeModifyColumn:
		stmt, err := modifyColumnStatement(alter, change.Column)
		if err != nil {
			return nil, err
		}
		return []string{stmt}, nil

	case domain.SchemaChangeTypeAddIndex:
		stmt, err := createIndexStatement(table, change.Index)
		if err != nil {
			return nil, err
		}
		return []string{stmt}, nil

	case domain.SchemaChangeTypeDropIndex:
		if change.Index.Name == "" {
			return nil, invalidSchema("index name is required")
		}
		// An index lives in its table's schema.
		name := quoteIdent(change.Index.Name)
		if dot := strings.LastIndexByte(table, '.'); dot >= 0 {
			name = quoteTable(table[:dot]) + "." + name
		}
		return []string{"DROP INDEX " + name}, nil

	case domain.SchemaChangeTypeAddConstraint:
		def, err := constraintDefinition(change.Constraint)
		if err != nil {
			return nil, err
		}
		return []string{alter + "ADD " + def}, nil

	case domain.SchemaChangeTypeDropConstraint:
		if change.Constraint.Name == "" {
			return nil, invalidSchema("constraint name is required")
		}
		return []string{alter + "DROP CONSTRAINT " + quoteIdent(change.Constraint.Name)}, nil

	default:
		return nil, domain.NewUnsupportedOperationError(fmt.Sprintf("schema change type %d", change.Type))
	}
}

// modifyColumnStatement changes a column to match col: its type, nullability
// and default. Primary key and identity are not altered (use constraints);
// identity columns keep their generated default.
func modifyColumnStatement(alter string, col domain.ColumnDefinition) (string, error) {
	if col.Name == "" {
		return "", invalidSchema("column name is required")
	}

	column := "ALTER COLUMN " + quoteIdent(col.Name) + " "
	actions := []string{column + "TYPE " + columnType(col)}
	if col.Nullable && !col.PrimaryKey && !col.AutoIncrement {
		actions = append(actions, column+"DROP NOT NULL")
	} else {
		actions = append(actions, column+"SET NOT NULL")
	}
	if !col.AutoIncrement {
		if col.DefaultValue == nil {
			actions = append(actions, column+"DROP DEFAULT")
		} else {
			literal, err := quoteLiteral(col.DefaultValue)
			if err != nil {
				return "", invalidSchema("column %s: %v", col.Name, err)
			}
			actions = append(actions, column+"SET DEFAULT "+literal)
		}
	}
	return alter + strings.Join(actions, ", "), nil
}

func createIndexStatement(table string, idx domain.IndexDefinition) (string, error) {
	if len(idx.Columns) == 0 {
		return "", invalidSchema("index %q has no columns", idx.Name)
	}

	var method string
	switch idx.Type {
	case domain.IndexTypeBTree:
		method = "btree"
	case domain.IndexTypeHash:
		method = "hash"
	case domain.IndexTypeGIN:
		method = "gin"
	case domain.IndexTypeGiST:
		method = "gist"
	default:
		return "", invalidSchema("unsupported index type %d", idx.Type)
	}

	var b strings.Builder
	b.WriteString("CREATE ")
	if idx.Unique {
		b.WriteString("UNIQUE ")
	}
	b.WriteString("INDEX ")
	if idx.Name != "" {
		b.WriteString(quoteIdent(idx.Name) + " ")
	}
	fmt.Fprintf(&b, "ON %s USING %s (%s)", quoteTable(table), method, quoteIdents(idx.Columns))
	return b.String(), nil
}

// constraintDefinition renders a table constraint.
func constraintDefinition(c domain.ConstraintDefinition) (string, error) {
	var b strings.Builder
	if c.Name != "" {
		b.WriteString("CONSTRAINT " + quoteIdent(c.Name) + " ")
	}

	if c.Type == domain.ConstraintTypeCheck {
		// ConstraintDefinition has no field for the CHECK expression.
		return "", domain.NewUnsupportedOperationError("CHECK constraint (no expression in ConstraintDefinition)")
	}
	if len(c.Columns) == 0 {
		return "", invalidSchema("constraint %q has no columns", c.Name)
	}

	switch c.Type {
	case domain.ConstraintTypePrimaryKey:
		b.WriteString("PRIMARY KEY (" + quoteIdents(c.Columns) + ")")
	case domain.ConstraintTypeUnique:
		b.WriteString("UNIQUE (" + quoteIdents(c.Columns) + ")")
	case domain.ConstraintTypeForeignKey:
		if c.RefTable == "" {
			return "", invalidSchema("foreign key %q has no referenced table", c.Name)
		}
		b.WriteString("FOREIGN KEY (" + quoteIdents(c.Columns) + ") REFERENCES " + quoteTable(c.RefTable))
		if len(c.RefColumns) > 0 {
			b.WriteString(" (" + quoteIdents(c.RefColumns) + ")")
		}
		for _, ref := range []struct {
			clause string
			action domain.ReferentialAction
		}{{"ON UPDATE", c.OnUpdate}, {"ON DELETE", c.OnDelete}} {
			action, err := referentialAction(ref.action)
			if err != nil {
				return "", err
			}
			if action != "" {
				b.WriteString(" " + ref.clause + " " + action)
			}
		}
	default:
		return "", invalidSchema("unsupported constraint type %d", c.Type)
	}
	return b.String(), nil
}

// referentialAction renders an ON UPDATE/ON DELETE action; NO ACTION, the
// default, renders as "".
func referentialAction(a domain.ReferentialAction) (string, error) {
	switch a {
	case domain.ReferentialActionNoAction:
		return "", nil
	case domain.ReferentialActionRestrict:
		return "RESTRICT", nil
	case domain.ReferentialActionCascade:
		return "CASCADE", nil
	case domain.ReferentialActionSetNull:
		return "SET NULL", nil
	case domain.ReferentialActionSetDefault:
		return "SET DEFAULT", nil
	default:
		return "", invalidSchema("unsupported referential action %d", a)
	}
}

func quoteIdents(names []string) string {
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = quoteIdent(name)
	}
	return strings.Join(quoted, ", ")
}

// columnType maps a column's domain type to a PostgreSQL type.
func columnType(col domain.ColumnDefinition) string {
	switch col.DataType {
	case domain.DataTypeString:
		if col.Length > 0 {
			return fmt.Sprintf("VARCHAR(%d)", col.Length)
		}
		return "TEXT"
	case domain.DataTypeInteger:
		return "INTEGER"
	case domain.DataTypeFloat:
		return "DOUBLE PRECISION"
	case domain.DataTypeBoolean:
		return "BOOLEAN"
	case domain.DataTypeDateTime:
		return "TIMESTAMP"
	case domain.DataTypeDate:
		return "DATE"
	case domain.DataTypeTime:
		return "TIME"
	case domain.DataTypeBinary:
		return "BYTEA"
	case domain.DataTypeJSON:
		return "JSONB"
	case domain.DataTypeUUID:
		return "UUID"
	case domain.DataTypeArray:
		return "TEXT[]"
	case domain.DataTypeDecimal:
		switch {
		case col.Precision > 0 && col.Scale > 0:
			return fmt.Sprintf("NUMERIC(%d,%d)", col.Precision, col.Scale)
		case col.Precision > 0:
			return fmt.Sprintf("NUMERIC(%d)", col.Precision)
		}
		return "NUMERIC"
	default: // DataTypeText and unknown types
		return "TEXT"
	}
}

// quoteLiteral renders v as an SQL literal for a DEFAULT clause: strings and
// []byte are quoted and escaped, numbers and booleans are rendered verbatim, and
// driver.Valuer values are rendered from their driver value.
func quoteLiteral(v interface{}) (string, error) {
	switch x := v.(type) {
	case nil:
		return "NULL", nil
	case string:
		return quoteString(x)
	case []byte:
		return quoteString(`\x` + hex.EncodeToString(x)) // bytea hex input
	case bool:
		if x {
			return "TRUE", nil
		}
		return "FALSE", nil
	case time.Time:
		return quoteString(x.Format("2006-01-02 15:04:05.999999999Z07:00"))
	case driver.Valuer:
		value, err := x.Value()
		if err != nil {
			return "", err
		}
		if _, nested := value.(driver.Valuer); nested {
			return "", fmt.Errorf("unsupported default value %T", v)
		}
		return quoteLiteral(value)
	}

	rv := reflect.ValueOf(v)
	switch rv.Kind() {
	case reflect.String:
		return quoteString(rv.String())
	case reflect.Bool:
		return quoteLiteral(rv.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(rv.Int(), 10), nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		return strconv.FormatUint(rv.Uint(), 10), nil
	case reflect.Float32, reflect.Float64:
		f := rv.Float()
		switch {
		case math.IsNaN(f):
			return "'NaN'", nil
		case math.IsInf(f, 1):
			return "'Infinity'", nil
		case math.IsInf(f, -1):
			return "'-Infinity'", nil
		}
		return strconv.FormatFloat(f, 'g', -1, rv.Type().Bits()), nil
	}
	return "", fmt.Errorf("unsupported default value type %T", v)
}

// quoteString quotes s as a string literal that is safe whatever the server's
// standard_conforming_strings setting: quotes are doubled and, if s contains a
// backslash, backslashes are doubled inside an escape string (E'...').
func quoteString(s string) (string, error) {
	if strings.IndexByte(s, 0) >= 0 {
		return "", fmt.Errorf("string literal contains a NUL byte")
	}
	s = strings.ReplaceAll(s, "'", "''")
	if strings.Contains(s, `\`) {
		return "E'" + strings.ReplaceAll(s, `\`, `\\`) + "'", nil
	}
	return "'" + s + "'", nil
}
