func TestQuoteLiteral(t *testing.T) {
	type level int
	type status string
	tests := []struct {
		value any
		want  string
	}{
		{nil, "NULL"},
		{"active", "'active'"},
		{"it's", "'it''s'"},
		{"'); DROP TABLE users; --", "'''); DROP TABLE users; --'"},
		{`back\slash`, `E'back\\slash'`},
		{`\'`, `E'\\'''`},
		{true, "TRUE"},
		{false, "FALSE"},
		{42, "42"},
		{int64(-7), "-7"},
		{uint64(math.MaxUint64), "18446744073709551615"},
		{1.5, "1.5"},
		{float32(0.25), "0.25"},
		{math.NaN(), "'NaN'"},
		{math.Inf(1), "'Infinity'"},
		{math.Inf(-1), "'-Infinity'"},
		{[]byte{0x01, 0xab}, `E'\\x01ab'`},
		{time.Date(2025, 1, 2, 3, 4, 5, 600, time.UTC), "'2025-01-02 03:04:05.0000006Z'"},
		{level(3), "3"},
		{status("on"), "'on'"},
		{valuer{s: "x'y"}, "'x''y'"},
	}
	for _, tt := range tests {
		got, err := quoteLiteral(tt.value)
		require.NoError(t, err, "%#v", tt.value)
		assert.Equal(t, tt.want, got, "%#v", tt.value)
	}

	for _, bad := range []any{map[string]int{}, struct{}{}, "nul\x00byte", valuer{nested: true}} {
		_, err := quoteLiteral(bad)
		assert.Error(t, err, "%#v", bad)
	}
}

type valuer struct {
	s      string
	nested bool
}

func (v valuer) Value() (driver.Value, error) {
	if v.nested {
		return valuer{}, nil
	}
	return v.s, nil
}

func TestCreateTableStatements(t *testing.T) {
	statements, err := createTableStatements(domain.TableSchema{
		Name: "app.users",
		Columns: []domain.ColumnDefinition{
			{Name: "id", DataType: domain.DataTypeInteger, PrimaryKey: true, AutoIncrement: true},
			{Name: "email", DataType: domain.DataTypeString, Length: 255},
			{Name: "status", DataType: domain.DataTypeString, DefaultValue: "it's new", Nullable: true},
			{Name: "balance", DataType: domain.DataTypeDecimal, Precision: 10, Scale: 2, DefaultValue: 0},
			{Name: "Weird\"Name", DataType: domain.DataTypeBoolean, DefaultValue: true},
		},
		Indexes: []domain.IndexDefinition{
			{Name: "users_email_idx", Columns: []string{"email"}, Unique: true},
			{Columns: []string{"status", "balance"}, Type: domain.IndexTypeHash},
		},
		Constraints: []domain.ConstraintDefinition{
			{Name: "users_email_key", Type: domain.ConstraintTypeUnique, Columns: []string{"email"}},
			{Name: "users_org_fk", Type: domain.ConstraintTypeForeignKey, Columns: []string{"id"},
				RefTable: "orgs", RefColumns: []string{"owner_id"}, OnDelete: domain.ReferentialActionCascade},
		},
	})
	require.NoError(t, err)
	assert.Equal(t, []string{
		`CREATE TABLE "app"."users" (` +
			`"id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, ` +
			`"email" VARCHAR(255) NOT NULL, ` +
			`"status" TEXT DEFAULT 'it''s new', ` +
			`"balance" NUMERIC(10,2) NOT NULL DEFAULT 0, ` +
			`"Weird""Name" BOOLEAN NOT NULL DEFAULT TRUE, ` +
			`CONSTRAINT "users_email_key" UNIQUE ("email"), ` +
			`CONSTRAINT "users_org_fk" FOREIGN KEY ("id") REFERENCES "orgs" ("owner_id") ON DELETE CASCADE)`,
		`CREATE UNIQUE INDEX "users_email_idx" ON "app"."users" USING btree ("email")`,
		`CREATE INDEX ON "app"."users" USING hash ("status", "balance")`,
	}, statements)
}

